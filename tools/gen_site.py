#!/usr/bin/env python3
"""Builds changelog.html (the website's changelog page) from the addon's CHANGELOG.md.

The rest of the website (index.html, assets/) is edited by hand. It reads only the Markdown CHANGELOG.md
uses: ## and ### headings, "-" lists (nested by two spaces), paragraphs, `code`, **bold**, [links](url) and
backslash escapes. No dependencies.

Usage: tools/gen_site.py [path/to/CHANGELOG.md]
  With no path it downloads CHANGELOG.md from the addon repository's main branch on GitHub.
  Pass a local path to build from a changelog that isn't pushed yet.
"""
import html
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "changelog.html"
CHANGELOG_URL = "https://raw.githubusercontent.com/ProfessionsForever/Professions_Forever/main/CHANGELOG.md"


def inline(text):
	"""Escapes text and applies inline Markdown: code spans first, so their contents stay literal."""
	parts = re.split(r"(`[^`]+`)", text)
	out = []
	for part in parts:
		if part.startswith("`") and part.endswith("`") and len(part) > 1:
			out.append("<code>" + html.escape(part[1:-1]) + "</code>")
			continue
		part = re.sub(r"\\([\\`*_{}\[\]()#+\-.!<>])", lambda m: "\x00%d\x00" % ord(m.group(1)), part)
		part = html.escape(part, quote=False)
		part = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", part)
		part = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: '<a href="%s">%s</a>' % (html.escape(m.group(2)), m.group(1)), part)
		part = re.sub(r"\x00(\d+)\x00", lambda m: html.escape(chr(int(m.group(1)))), part)
		out.append(part)
	return "".join(out)


def slug(text):
	return "v" + re.sub(r"[^0-9a-z]+", "-", text.lower()).strip("-")


def convert(md):
	"""Returns (body html, [(version, id)])."""
	body, versions = [], []
	depth = 0  # open <ul> levels
	in_li = [False] * 8
	para = []

	def close_lists(to=0):
		nonlocal depth
		while depth > to:
			if in_li[depth]:
				body.append("</li>")
				in_li[depth] = False
			body.append("</ul>")
			depth -= 1

	def flush_para():
		if para:
			body.append("<p>" + inline(" ".join(para)) + "</p>")
			para.clear()

	for raw in md.splitlines():
		line = raw.rstrip()
		if not line.strip():
			flush_para()
			continue
		m = re.match(r"^(#{1,4})\s+(.*)$", line)
		if m:
			flush_para()
			close_lists()
			level, text = len(m.group(1)), m.group(2).strip()
			if level == 1:
				continue  # the page has its own title
			if level == 2:
				vid = slug(text)
				versions.append((text, vid))
				extra = ' <span class="badge">LATEST</span>' if len(versions) == 1 else ""
				body.append('<h2 id="%s">%s%s</h2>' % (vid, inline(text), extra))
			else:
				body.append("<h%d>%s</h%d>" % (level, inline(text), level))
			continue
		m = re.match(r"^( *)- (.*)$", line)
		if m:
			flush_para()
			level = len(m.group(1)) // 2 + 1
			if level > depth:
				while depth < level:
					depth += 1
					body.append("<ul>")
			else:
				close_lists(level)
				if in_li[level]:
					body.append("</li>")
			body.append("<li>" + inline(m.group(2)))
			in_li[level] = True
			continue
		if depth and raw.startswith(" "):
			body[-1] += " " + inline(line.strip())  # continuation of a list item
			continue
		close_lists()
		para.append(line.strip())
	flush_para()
	close_lists()
	return "\n".join(body), versions


