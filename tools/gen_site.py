def main():
	if len(sys.argv) > 1:
		md = Path(sys.argv[1]).read_text(encoding="utf-8")
	else:
		print("Downloading %s" % CHANGELOG_URL)
		with urllib.request.urlopen(CHANGELOG_URL, timeout=30) as resp:
			md = resp.read().decode("utf-8")
	body, versions = convert(md)
	toc = "\n".join('\t\t\t<li><a href="#%s">%s</a></li>' % (vid, html.escape(v)) for v, vid in versions)
	OUT.write_text(PAGE % {"toc": toc, "body": body}, encoding="utf-8")
	print("Wrote %s (%d versions)" % (OUT.relative_to(ROOT), len(versions)))


if __name__ == "__main__":
	main()
